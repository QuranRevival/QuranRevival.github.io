// QR J02 S3: the "shell" the offline worker saves at install for Quran Study, LDOG and the pages they open: each
// page, every script it reaches (static, dynamic and re-exported imports), and the stylesheets, fonts, images and
// vendor files they link. Never the Qur'an or hadith DATA (57 MB + 37 MB: kept on first use instead).
// Asma's own list stays in app/sw.js unchanged; anything already in it is left out here.
//
//   node tools/qr-sw/make-precache.mjs           writes the version and the shell into app/sw.js's generated block
//   node tools/qr-sw/make-precache.mjs --check   exit 1 if that block is not what it would write (npm test runs it)
import fs from "node:fs";
import path from "node:path";

export const PAGES = ["quranrevival.html", "ldog-study.html", "notes.html", "bookmarks.html", "journey-map.html", "records.html", "monitor.html", "about.html", "onboarding.html", "import-notes.html", "accept-invite.html"];
const re = /(?:(?:import|export)\s[^'"]*?from\s*|import\s*\(\s*|import\s+)["'](\.{1,2}\/[^"']+\.js)["']/g;

export function shellList() {
  const seen = new Set();
  const walk = (f) => {
    if (seen.has(f)) return; seen.add(f);
    for (const m of fs.readFileSync(f, "utf8").matchAll(re)) { const p = path.normalize(path.join(path.dirname(f), m[1])); if (fs.existsSync(p)) walk(p); }
  };
  const extra = new Set();
  for (const page of PAGES) {
    walk(`app/${page}`);
    const html = fs.readFileSync(`app/${page}`, "utf8");
    for (const m of html.matchAll(/(?:href|src)="(?:\.\/)?((?:css|vendor|img|fonts)\/[^"#?]+)"/g)) extra.add(`app/${m[1]}`);
    for (const m of html.matchAll(/url\(['"]?(?:\.\/)?(fonts\/[^'")]+)['"]?\)/g)) extra.add(`app/${m[1]}`);
  }
  for (const css of [...extra].filter((f) => f.endsWith(".css"))) {
    for (const m of fs.readFileSync(css, "utf8").matchAll(/url\(['"]?\.\.\/((?:fonts|img)\/[^'")]+)['"]?\)/g)) extra.add(`app/${m[1]}`);
  }
  const sw = fs.readFileSync("app/sw.js", "utf8");
  const asma = new Set([...sw.slice(sw.indexOf("const PRECACHE = ["), sw.indexOf("];", sw.indexOf("const PRECACHE = ["))).matchAll(/"([^"]+)"/g)].map((m) => m[1]));
  return [...new Set([...seen, ...extra])].filter((f) => fs.existsSync(f)).map((f) => path.relative("app", f)).filter((f) => !asma.has(f)).sort();
}

/** app/sw.js with its generated block (the version and the shell) filled in. */
export function swWithBlock(list) {
  const sw = fs.readFileSync("app/sw.js", "utf8");
  const version = fs.readFileSync("app/js/qr-version.js", "utf8").match(/APP_VERSION = "([\d.]+)"/)[1];
  const a = sw.indexOf("// BEGIN GENERATED BY tools/qr-sw/make-precache.mjs");
  const b = sw.indexOf("// END GENERATED", a);
  if (a < 0 || b < 0) throw new Error("app/sw.js has no generated block");
  const bytes = list.reduce((n, f) => n + fs.statSync(path.join("app", f)).size, 0);
  const block = `// BEGIN GENERATED BY tools/qr-sw/make-precache.mjs
const APP_VERSION = ${JSON.stringify(version)}; // = app/js/qr-version.js
// The shell of Quran Study, LDOG and the pages they open, saved at install besides Asma's list: ${list.length} files, ${(bytes / 1e6).toFixed(2)} MB.
const SHELL = ${JSON.stringify(list, null, 2)};
`;
  return { text: sw.slice(0, a) + block + sw.slice(b), version, bytes };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const list = shellList();
  const { text, version, bytes } = swWithBlock(list);
  const same = fs.readFileSync("app/sw.js", "utf8") === text;
  if (process.argv.includes("--check")) {
    console.log(`${same ? "ok  " : "FAIL"} app/sw.js's generated block is up to date (version ${version}, ${list.length} shell files, ${(bytes / 1e6).toFixed(2)} MB)`);
    process.exit(same ? 0 : 1);
  }
  fs.writeFileSync("app/sw.js", text);
  console.log(`app/sw.js: version ${version}, ${list.length} shell files, ${(bytes / 1e6).toFixed(2)} MB`);
}
