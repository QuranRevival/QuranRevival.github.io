// QR J01 R3: builds app/js/asma-screensaver-qr.js from MMSA's app/js/asma-screensaver.js.
//
// MMSA's file cannot be copied unchanged: it statically imports session-context.js (and through it Firebase) to read
// the madrasah's Names document and the person's records. QR's Asma app has no sign-in, so the copy is MMSA's file
// with only the changes below, each applied exactly once (the build stops if MMSA's text has moved):
//   1. no session-context.js import;
//   2. loadScreensaverData() reads from a provider the page sets (the seed groups and this device's Studied ticks)
//      instead of Firestore;
//   3. "Open this Name" opens it in the Asma app (#v=name&n=N), not asma-study.html;
//   4. "⚙ Settings" → "Start now" restarts through QR's own watcher (qr-screensaver.js);
//   5. a tap on the poster or any key other than ← → space closes it (the controls show for the first moments
//      and whenever the pointer moves), as the QR Architect asked: "any tap or key closes it";
//   6. no "Where it may start" row: QR has one page.
// Everything else (the deck, the order, the timings, the settings panel and its storage) is MMSA's code unchanged.
//
//   node tools/qr-asma/make-screensaver.mjs <MMSA checkout>          writes the file
//   node tools/qr-asma/make-screensaver.mjs <MMSA checkout> --check  exit 1 if the file is not what it would write
import fs from "node:fs";
import path from "node:path";

const HEADER = `// QR J01 R3 (QR-only, GENERATED by tools/qr-asma/make-screensaver.mjs from MMSA's app/js/asma-screensaver.js; do
// not edit by hand). MMSA's screensaver with no Firebase: the Names, groups and Studied ticks come from the Asma app
// (setScreensaverDataSource), and a tap or key closes it. See the tool's header for the exact changes.
`;
const EDITS = [
  ['import { getActiveContext } from "./session-context.js";\n', ""],
  [/let dataCache = null;\n\n\/\*\* Reads, once per tenant[\s\S]*?\n  dataCache = \{ key, promise \};\n  return promise;\n\}\n/, `/** QR: where the screensaver's Names, groups and Studied ticks come from (the Asma app sets it; no sign-in). */
let dataSource = () => ({ entries: null, groups: [], studied: null, failed: false });
export function setScreensaverDataSource(fn) { dataSource = fn; }

/** Never throws: \`failed\` says the data could not be read, and the callers fall back to all the Names. */
export function loadScreensaverData() {
  return Promise.resolve().then(() => dataSource()).catch((err) => {
    console.warn("screensaver: could not read the Names (showing all the Names instead):", err?.message || err);
    return { entries: null, groups: [], studied: null, failed: true };
  });
}
`],
  ['location.href = `./asma-study.html?name=${Number(s.entry.number)}&back=1`;', 'location.hash = `v=name&n=${Number(s.entry.number)}`;'],
  ['import("./screensaver-idle.js").then((m) => m.startScreensaver({ entries, ...o }))', 'import("./qr-screensaver.js").then((m) => m.startScreensaver({ entries, ...o }))'],
  ['root.addEventListener("pointerdown", (e) => { if (!e.target.closest("button")) showCtl(); });', 'root.addEventListener("click", (e) => { if (!e.target.closest("button")) close(); });'],
  ['    else showCtl();\n  };', '    else if (e.key === "Tab" || (e.key === "Enter" && e.target.closest?.("#mmSaver button"))) showCtl();\n    else { e.preventDefault(); close(); }\n  };'],
  ['  tick();\n  keepAwake();', '  tick();\n  showCtl();\n  keepAwake();'],
  ['    ${row("Where it may start", seg("where"), "Never while a recitation plays, while you write on the Writing sheet, or while you type.")}\n', ""],
];

const mmsa = process.argv[2];
if (!mmsa) { console.error("Usage: node tools/qr-asma/make-screensaver.mjs <MMSA checkout> [--check]"); process.exit(2); }
let src = fs.readFileSync(path.join(mmsa, "app/js/asma-screensaver.js"), "utf8");
for (const [from, to] of EDITS) {
  const hits = typeof from === "string" ? src.split(from).length - 1 : (src.match(new RegExp(from.source, "g")) || []).length;
  if (hits !== 1) { console.error(`An edit no longer applies exactly once (${hits}): ${String(from).slice(0, 80)}`); process.exit(1); }
  src = src.replace(from, to);
}
const out = HEADER + src;
const target = "app/js/asma-screensaver-qr.js";
if (process.argv.includes("--check")) {
  const same = fs.existsSync(target) && fs.readFileSync(target, "utf8") === out;
  console.log(`${same ? "ok  " : "FAIL"} ${target} is MMSA's asma-screensaver.js with exactly the ${EDITS.length} QR edits`);
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(target, out);
console.log(`${target} written (${EDITS.length} edits on MMSA's file)`);
